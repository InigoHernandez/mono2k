static int grids_pert(uint32_t cycle, int part, int chaos)
{
    uint32_t h = cycle * 0x9E3779B1u + (uint32_t)part * 0x85EBCA77u + 0x2545F491u;
    h ^= h >> 16; h *= 0x7FEB352Du; h ^= h >> 15; h *= 0x846CA68Bu; h ^= h >> 16;
    return (int)(((h >> 24) * (uint32_t)(chaos >> 2)) >> 8);
}

/* the level once raised: past the top it is the top (Grids' own clipping, not Anushri's) */
static int grids_level(int step, int part, int x, int y, int pert)
{
    int l = grids_read(step, part, x, y);
    return l < 255 - pert ? l + pert : 255;
}

/* a knob's 0..127 on Grids' 0..255 (64 the middle node, 127 the far edge) */
static inline int gr8(int v) { return v * 255 / 127; }
