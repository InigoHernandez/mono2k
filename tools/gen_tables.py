# MONO2K's lookup tables: everything the integer DSP would otherwise need floating point for.
# Writes firmware/gen/m2k_tables.h.
import cmath, json, math, os, sys, random

SR = 44100
SUB = 16
OUT = os.path.join(os.path.dirname(__file__), "..", "firmware", "gen", "m2k_tables.h")


def arr(name, ctype, vals, per=12):
    s = "static const %s %s[%d] = {\n" % (ctype, name, len(vals))
    for i in range(0, len(vals), per):
        s += "    " + ", ".join(str(int(v)) for v in vals[i:i + per]) + ",\n"
    return s + "};\n"


def clamp(v, lo, hi):
    return max(lo, min(hi, v))


out = ["/* generated by tools/gen_tables.py: do not edit */\n#include <stdint.h>\n"]

# sine, 1024 + guard, full scale 32767
out.append(arr("T_SIN", "int16_t", [round(32767 * math.sin(2 * math.pi * i / 1024)) for i in range(1025)]))

# phase increments for the top octave (MIDI 120..132) in 1/64 semitones; lower octaves shift right
top = []
for i in range(769):
    f = 440.0 * 2 ** ((120 + i / 64.0 - 69) / 12.0)
    top.append(min(0xFFFFFFFF, round(f / SR * 2 ** 32)))
out.append(arr("T_INC_TOP", "uint32_t", top, 8))

# envelope times: t(v) = 1 ms * 2^(v / 10); 0 is ~0.3 ms
def etime(v):
    return 0.0003 if v == 0 else 0.001 * 2 ** (v / 10.0)
# linear rise per control block, full scale 2^30
out.append(arr("T_ENV_INC", "uint32_t", [min(1 << 30, round((1 << 30) * SUB / (etime(v) * SR))) for v in range(128)], 8))
# exponential fall per control block to -60 dB in t(v), Q31 multiplier
out.append(arr("T_ENV_COEF", "uint32_t",
               [round((2 ** 31 - 1) * math.exp(-6.9078 * SUB / (etime(v) * SR))) for v in range(128)], 8))
# the times as the screen shows them, in ms (0.1 ms below 10)
out.append(arr("T_ENV_MS10", "uint32_t", [round(etime(v) * 10000) for v in range(128)], 8))

# the amp envelope, after the Monomachine's, measured on OS 1.32B in gearmulator (tools/ref, amp.spec, hold.spec):
#   the attack rises in a straight line, in 0.90 ms * e^(0.0814 v); decay and release fall 20 dB in 8.3 ms * e^(0.0665 v)
#   (here: to -60 dB, three times that); the hold lasts 14.6 ms a step. 127: hold and decay last while the gate is open.
def a_atk(v):
    return 0.000903 * math.exp(0.0814 * v)
def a_dec(v):
    return 3 * 0.00829 * math.exp(0.06646 * v)
def a_hold(v):                         # HOLD up to format 12, 14.6 ms a step (format 13: 1 / 32 beat, in the engine)
    return 0.0146 * v
out.append(arr("T_AATK_INC", "uint32_t", [min(1 << 30, round((1 << 30) * SUB / (a_atk(v) * SR))) for v in range(128)], 8))
out.append(arr("T_ADEC_COEF", "uint32_t", [round((2 ** 31 - 1) * math.exp(-6.9078 * SUB / (a_dec(v) * SR))) for v in range(128)], 8))
out.append(arr("T_AATK_MS10", "uint32_t", [round(a_atk(v) * 10000) for v in range(128)], 8))
out.append(arr("T_ADEC_MS10", "uint32_t", [round(a_dec(v) * 10000) for v in range(128)], 8))
# the modulation effect's sweep: 0.1 Hz .. 10 Hz, as a phase step per sample, and for the screen in 0.1 Hz
def mod_hz(v):
    return 0.1 * 100 ** (v / 127.0)
out.append(arr("T_MOD_INC", "uint32_t", [round(mod_hz(v) / SR * 2 ** 32) for v in range(128)], 8))
out.append(arr("T_MOD_HZ10", "uint16_t", [max(1, round(mod_hz(v) * 10)) for v in range(128)]))
# its chorus and flanger across the stereo (MONO2K's own): the side through two one-pole high-passes at 160 Hz (Q24), so
# the low end stays in the middle (-20 dB at 50 Hz)
out.append("#define MOD_SIDE_HP %d\n" % round((1 - math.exp(-2 * math.pi * 160 / SR)) * 2 ** 24))
# SWAV-SAW, after the Monomachine's SWAVE-SAW (measured on OS 1.32B, tools/ref/swave_saw*.spec): the unison pair's
# pitch ratios a step of UNIW (-0.4168 c below, +0.4276 c above), the extended pair's (+-0.2109 c), Q24
out.append(arr("T_SW1LO", "uint32_t", [round(2 ** 24 * 2 ** (-0.4168 * v / 1200)) for v in range(128)], 8))
out.append(arr("T_SW1HI", "uint32_t", [round(2 ** 24 * 2 ** (0.4276 * v / 1200)) for v in range(128)], 8))
out.append(arr("T_SW2LO", "uint32_t", [round(2 ** 24 * 2 ** (-0.2109 * v / 1200)) for v in range(128)], 8))
out.append(arr("T_SW2HI", "uint32_t", [round(2 ** 24 * 2 ** (0.2109 * v / 1200)) for v in range(128)], 8))
# its highpass, a pole that follows the note: cutoff (0.98 + 0.0223 (note - 24)) x f0, as the coefficient a (Q15)
def sw_hp(n):
    f0 = 440 * 2 ** ((n - 69) / 12)
    r = min(2.6, max(0.9, 0.98 + 0.0223 * (n - 24)))
    return round(32768 * math.exp(-2 * math.pi * min(r * f0, SR * 0.45) / SR))
out.append(arr("T_SWHP", "uint16_t", [min(32767, sw_hp(n)) for n in range(128)]))
# SUBX's level against its setting (measured: dB from full at 8 16 24 32 48 64 80 96 112 127), Q15
_sx = [(0, -120), (8, -12.9), (16, -8.4), (24, -6.3), (32, -5.0), (48, -3.4), (64, -2.4), (80, -1.7), (96, -1.0), (112, -0.5), (127, 0)]
def subx(v):
    for (a0, d0), (a1, d1) in zip(_sx, _sx[1:]):
        if a0 <= v <= a1:
            if v == 0: return 0
            d = d0 + (d1 - d0) * (v - a0) / (a1 - a0) if a0 else d1 * v / a1 + 20 * math.log10(max(v, 1) / a1)
            return round(32767 * 10 ** (d / 20))
out.append(arr("T_SWSUBX", "uint16_t", [subx(v) for v in range(128)]))
# patterns saved before (version 1) timed ATK HOLD DEC REL on etime(): each value to the one nearest its time
def nearest(t, f, lo=0, hi=126):
    return min(range(lo, hi + 1), key=lambda v: abs(math.log(max(f(v), 1e-6)) - math.log(max(t, 1e-6))))
v1 = [[nearest(etime(v), a_atk) for v in range(128)],
      [0 if v == 0 else 127 if v == 127 else nearest(etime(v), a_hold, 1) for v in range(128)],
      [127 if v == 127 else nearest(etime(v), a_dec) for v in range(128)],
      [nearest(etime(v), a_dec) for v in range(128)]]
out.append("static const uint8_t T_AMPV1[4][128] = {\n" + "".join("    {" + ",".join(str(x) for x in r) + "},\n" for r in v1) + "};\n")
# portamento: per control block, Q16 share of the distance left
out.append(arr("T_GLIDE", "uint16_t",
               [65535 if v == 0 else round(65536 * (1 - math.exp(-SUB / (0.0008 * 2 ** (v / 13.0) * SR)))) for v in range(128)]))

# filter cutoff: v (0..127, in 1/8 steps) -> 20 Hz .. 20 kHz; ZDF g = tan(pi fc / fs) in Q12, clamped below Nyquist
def fcut(q3):
    return 20.0 * 1000 ** (q3 / (127 * 8.0))
g = []
for q3 in range(127 * 8 + 1):
    fc = min(fcut(q3), 0.46 * SR)
    g.append(clamp(round(4096 * math.tan(math.pi * fc / SR)), 1, 32767))
out.append(arr("T_CUT_G", "uint16_t", g))
# the cutoff as the screen shows it, Hz
out.append(arr("T_HZ", "uint16_t", [round(fcut(v * 8)) for v in range(128)]))
# one-pole lowpass coefficient (Q15) for a cutoff step v at half rate (the delay lines and the bus)
out.append(arr("T_OP_H", "uint16_t", [round(32767 * (1 - math.exp(-2 * math.pi * min(fcut(v * 8), 10000) / (SR / 2)))) for v in range(128)]))
# and at full rate
out.append(arr("T_OP", "uint16_t", [round(32767 * (1 - math.exp(-2 * math.pi * min(fcut(v * 8), 20000) / SR))) for v in range(128)]))
# resonance: damping R in Q12, from 1.0 (flat) to 0.025 (ringing)
out.append(arr("T_RES_R", "uint16_t", [round(4096 * (1.0 * (0.025 / 1.0) ** (v / 127.0))) for v in range(128)]))

# soft saturation: input -131072..131072 in 257 steps of 1024, unity gain at zero, tanh shape
out.append(arr("T_SAT", "int16_t", [round(32767 * math.tanh((i - 128) / 32.0)) for i in range(257)]))

# constant-power pan, Q15
out.append(arr("T_PAN", "uint16_t", [round(32767 * math.cos(v / 127.0 * math.pi / 2)) for v in range(128)]))
# volume curve (squared), Q15
out.append(arr("T_VOL", "uint16_t", [round(32767 * (v / 127.0) ** 2) for v in range(128)]))

# ---- the track chain, after the Monomachine's (measured on OS 1.32B in gearmulator, tools/ref/chain.py and README)
def interp(pts, x, log=False):
    for (x0, y0), (x1, y1) in zip(pts, pts[1:]):
        if x0 <= x <= x1:
            t = (x - x0) / (x1 - x0)
            return math.exp(math.log(y0) + t * (math.log(y1) - math.log(y0))) if log else y0 + t * (y1 - y0)
    return pts[0][1] if x < pts[0][0] else pts[-1][1]
# DIST: below 64 headroom, 1.35 dB a step (63: -1.01 dB); 64..72 clean; above, gain into the clip (small signals:
# +1.95 dB at 76, +4.58 at 80, +10.55 at 88, then ~0.62 dB a step). The clip's ceiling, against a full-scale machine:
# +5.79 dB up to 64, falling to -3.24 dB at 80 and staying there. The gain Q24, the ceiling in machine units
def dist_h(d):
    if d < 64:
        return -1.35 * (64 - d) + 0.34
    if d >= 88:
        return 10.55 + (d - 88) * 0.62
    return interp([(64, 0), (72, 0), (76, 1.95), (80, 4.58), (84, 7.78), (88, 10.55)], d)
def dist_c(d):
    return 0.6 + interp([(64, 5.79), (68, 3.94), (72, 0.0), (76, -2.27), (80, -3.24)], d)
out.append(arr("T_DIST_H", "uint32_t", [round(2 ** 24 * 10 ** (dist_h(d) / 20)) for d in range(128)], 8))
out.append(arr("T_DIST_C", "int32_t", [round(32767 * 10 ** (dist_c(d) / 20)) for d in range(128)], 8))
# and the ceiling machine by machine (tools/ref/chain_dist21.spec): the Monomachine clips each machine against a
# ceiling of its own, whatever the level going in (a saw alone, with its subs or its unison all clip to the same level;
# a chord of one voice or four; a sine full or cut 15 dB). Against GND-SIN's, dB; Q12. In the machines' order
DIST_M = {"GSIN": 0.0, "GPRC": 0.0, "SID": 0.0, "FMS": -1.4, "FMD": 0.0, "SAW": -10.5, "ENS": 1.7, "WAV": -7.0, "VOX": -1.4,
          "FMP": 0.3, "PUL": -2.75, "FXC": 0.0, "FXR": 0.0, "FXD": 0.0, "GNOI": 0.0,
          "DKIK": 0.0, "DSNR": 0.0, "DHAT": 0.0, "DCYM": 0.0}
out.append(arr("T_DIST_M", "uint16_t", [round(4096 * 10 ** (v / 20)) for v in DIST_M.values()], 14))
# the DRM- machines (voice design after the Erica Synths LXR drum voices, GPL-3.0-only): its time law, (127 + K v) /
# (2 (127 - v)) of its 64-sample blocks (at least one), as a ramp's fall per 16-sample block, Q30: K 198 for the
# sweeps, the attacks and the clap's spacing, K 1998 for the amp's decays; 127 as 126 (the LXR's 127 never moves) but
# the decay's, which holds (INF). The times in 0.1 ms for the screen. The sweep's depth A = 32 (v / 127)^2, Q8. The
# snare's noise filter: from 18 kHz (its lowpass) and 100 Hz (its highpass), in the filters' positions, Q8
def lxr_blk(v, K):
    v = min(v, 126)
    return max(1.0, (127 + K * v) / (2.0 * (127 - v)))
out.append(arr("T_DRM_RA", "uint32_t", [round((1 << 30) / (4 * lxr_blk(v, 198))) for v in range(128)], 8))
out.append(arr("T_DRM_RD", "uint32_t", [0 if v == 127 else round((1 << 30) / (4 * lxr_blk(v, 1998))) for v in range(128)], 8))
out.append(arr("T_DRM_RA_MS10", "uint32_t", [round(lxr_blk(v, 198) * 64 / SR * 10000) for v in range(128)], 8))
out.append(arr("T_DRM_RD_MS10", "uint32_t", [round(lxr_blk(v, 1998) * 64 / SR * 10000) for v in range(128)], 8))
out.append(arr("T_DRM_PAMT", "uint16_t", [round(256 * 32 * (v / 127) ** 2) for v in range(128)], 12))
out.append("#define DRM_LP0 %d\n#define DRM_HP0 %d\n" % (round(96 * math.log2(18000 / 8.1758)) * 256,
                                                       round(96 * math.log2(100 / 8.1758)) * 256))
# GND-NOIS on the Monomachine's page (tools/ref/chain_gnoi42.spec): RED colours white noise towards pink (64) and red
# (127). White, pink (the economy pink filter: one-poles at 16.5, 264 and 3946 Hz and the white through it) and brown
# (the pink's 16.5 Hz one-pole, then one at 14 kHz over the top), each scaled to white's level at 1 kHz, mixed by weights
# fitted at every 16th RED (tools/ref/gnoi_fit.py) and interpolated between; Q14. The one-poles' G Q24, the gains Q12
GNOI_RED = (0, 16, 32, 48, 64, 80, 96, 112, 127)
GNOI_RED_W = [(1.0000, 0.0000, 0.0000), (0.7509, 0.4858, 0.0000), (0.5031, 0.9641, 0.0000), (0.2588, 1.4364, 0.0000),
              (0.0146, 1.9105, 0.0000), (0.0000, 1.4341, 0.0917), (0.0000, 0.9296, 0.2129), (0.0000, 0.4052, 0.3526),
              (0.0000, 0.0128, 0.4186)]
GNOI_PINK = ((16.5, 42.15), (264.0, 8.014), (3946.0, 2.448))
GNOI_PINK_W, GNOI_TOP = 0.1848, 14000.0
def gn_lp(f, fc):
    g = 1 - math.exp(-2 * math.pi * fc / SR)
    return g / (1 - (1 - g) * cmath.exp(-2j * math.pi * f / SR))
_pk1k = abs(GNOI_PINK_W + sum(k * gn_lp(1000.0, fc) for fc, k in GNOI_PINK))
_br1k = abs(gn_lp(1000.0, GNOI_PINK[0][0]) * gn_lp(1000.0, GNOI_TOP))
out.append("#define GN_G0 %d\n#define GN_G1 %d\n#define GN_G2 %d\n#define GN_GT %d\n" % tuple(
    round((1 - math.exp(-2 * math.pi * fc / SR)) * 2 ** 24) for fc in (GNOI_PINK[0][0], GNOI_PINK[1][0], GNOI_PINK[2][0], GNOI_TOP)))
out.append("#define GN_KW %d\n#define GN_K0 %d\n#define GN_K1 %d\n#define GN_K2 %d\n#define GN_KB %d\n" % (
    round(4096 * GNOI_PINK_W / _pk1k), round(4096 * GNOI_PINK[0][1] / _pk1k), round(4096 * GNOI_PINK[1][1] / _pk1k),
    round(4096 * GNOI_PINK[2][1] / _pk1k), round(4096 / _br1k)))
def gn_w(v):
    i = max(k for k in range(len(GNOI_RED)) if GNOI_RED[k] <= v)
    if i == len(GNOI_RED) - 1:
        return GNOI_RED_W[i]
    u = (v - GNOI_RED[i]) / (GNOI_RED[i + 1] - GNOI_RED[i])
    return tuple(a + (b - a) * u for a, b in zip(GNOI_RED_W[i], GNOI_RED_W[i + 1]))
out.append(arr("T_RED_W", "int16_t", [round(16384 * c) for v in range(128) for c in gn_w(v)], 12))
# the filter follows the note: a cutoff 2^((step - 16) / 8) x f0, the same for the HP (BASE) and the LP (BASE + WDTH).
# Positions in 1/96 octave over MIDI note 0 (8.18 Hz): 8 a semitone, 12 a step. Every section stops at 18 kHz,
# which gives the open filter the Monomachine's top (-1 dB at 12.5 kHz, -1.8 dB at 14 kHz). ZDF g = tan(pi fc / fs)
# for the two-poles, G = g / (1 + g) for the one-poles, both Q24 (a low cutoff keeps its precision)
F_TOP = round(96 * math.log2(18000 / 8.1758))
def fpos(i):
    return 8.1758 * 2 ** (min(i, F_TOP) / 96)
out.append("#define F_TOP %d\n" % F_TOP)
out.append(arr("T_FG", "uint32_t", [round(2 ** 24 * math.tan(math.pi * fpos(i) / SR)) for i in range(F_TOP + 1)], 8))
out.append(arr("T_FG1", "uint32_t", [round(2 ** 24 * math.tan(math.pi * fpos(i) / SR) / (1 + math.tan(math.pi * fpos(i) / SR))) for i in range(F_TOP + 1)], 8))
# the LP: a resonant two-pole (LP1) before the clip, two one-poles at 1.55 x the cutoff after it (LP2). LP1 sits at
# 1.35 x the cutoff with Q 0.74 at LPQ 0 and moves onto the cutoff as the Q rises (fits to the stepped sine and to
# noise with headroom); the HP alike: a resonant two-pole at 1.24 .. 1.0 x, and a one-pole at 1.75 x after the clip.
# Per Q value: the two-pole's offset in 1/96 octave Q8 and its damping 1/Q, Q24
# From Q 96 up both peaks sit 0.18 % under the cutoff (resolved on noise at C4 and C6, tools/ref/resfit.py). The
# reference's Q also moves with the cutoff (HPQ 96: ~230 at 8.4 kHz, ~160 at 4.2 kHz, ~190 at 131 Hz); one value
# per setting takes the middle
LPQ = [(0, .74), (8, .95), (16, 1.6), (24, 2.6), (32, 4.5), (40, 7.5), (48, 12.5), (56, 19), (64, 27.5), (72, 45), (80, 68),
       (88, 130), (96, 210), (104, 300), (112, 500), (120, 750), (127, 1000)]
LPC = [(0, 1.35), (8, 1.22), (16, 1.10), (24, 1.06), (32, 1.03), (40, 1.02), (48, 1.0), (64, 1.0), (80, 0.998), (96, 0.9982)]
HPQ = [(0, .80), (8, 1.03), (16, 1.43), (24, 1.9), (32, 3.5), (40, 5.6), (48, 8.7), (56, 15.6), (64, 30), (72, 50),
       (80, 85), (88, 140), (96, 190), (104, 340), (112, 486), (120, 800), (127, 1200)]
HPC = [(0, 1.24), (16, 1.26), (32, 1.114), (48, 1.0), (64, 0.994), (80, 0.999), (96, 0.9982)]
out.append(arr("T_LPK", "uint32_t", [round(2 ** 24 / interp(LPQ, q, True)) for q in range(128)], 8))
out.append(arr("T_HPK", "uint32_t", [round(2 ** 24 / interp(HPQ, q, True)) for q in range(128)], 8))
out.append(arr("T_LPC", "int16_t", [round(96 * 256 * math.log2(interp(LPC, q))) for q in range(128)], 16))
out.append(arr("T_HPC", "int16_t", [round(96 * 256 * math.log2(interp(HPC, q))) for q in range(128)], 16))
out.append("#define F_LP2 %d\n#define F_HP1 %d\n" % (round(96 * math.log2(1.55)), round(96 * math.log2(1.75))))
# the EQ: a band added to the signal, Q 2.2, a cut the exact inverse of a boost as deep; its
# centre 13.5 steps an octave, 808 Hz at 64 (fit to the measured centres). g Q24, the linear gain Q16, Hz for the screen
EQC = [(16, 65), (20, 75), (24, 105), (28, 132), (32, 172), (36, 191), (40, 223), (44, 301), (48, 353), (52, 468),
       (56, 544), (60, 630), (64, 829), (68, 991), (72, 1141), (76, 1556), (80, 1898), (84, 2336), (88, 2719),
       (92, 3488), (96, 3957), (100, 5370), (104, 6097), (108, 7749), (112, 9881), (116, 10882)]
_n = len(EQC); _sx = sum(v for v, _ in EQC); _sy = sum(math.log2(f) for _, f in EQC)
_sxx = sum(v * v for v, _ in EQC); _sxy = sum(v * math.log2(f) for v, f in EQC)
EQ_B = (_n * _sxy - _sx * _sy) / (_n * _sxx - _sx * _sx); EQ_A = (_sy - EQ_B * _sx) / _n
def eqf(v):
    return 2 ** (EQ_A + EQ_B * v)
out.append(arr("T_EQG", "uint32_t", [round(2 ** 24 * math.tan(math.pi * min(eqf(v), 18000) / SR)) for v in range(128)], 8))
# its gain, measured (a curve, not a straight line in dB): boost to +36.1 dB, cut to -31.1 dB
EQUP = [(0, 0), (8, 7.1), (16, 12.0), (24, 16.8), (32, 21.3), (40, 24.7), (48, 29.1), (56, 32.6), (63, 36.1)]
EQDN = [(0, 0), (8, 5.3), (16, 8.6), (24, 12.5), (32, 16.0), (40, 19.8), (48, 24.6), (56, 26.9), (64, 31.1)]
out.append(arr("T_EQGAIN", "uint32_t", [round(65536 * 10 ** (interp(EQUP if v > 64 else EQDN, abs(v - 64)) / 20)) for v in range(128)], 8))
out.append(arr("T_EQHZ", "uint16_t", [round(eqf(v)) for v in range(128)]))
# SRR: a sample and hold whose period runs from 1 sample (0) to 15.7 (127, 2.8 kHz); measured, smooth between. Q16
SRRP = [(0, 1.0), (16, 2.823), (24, 3.765), (32, 4.706), (40, 5.647), (48, 6.589), (56, 7.467), (64, 8.471), (72, 9.290),
        (80, 10.182), (88, 11.078), (96, 12.003), (104, 13.001), (112, 14.0), (120, 15.0), (127, 15.677)]
out.append(arr("T_SRR_INC", "uint32_t", [round(65536 / interp(SRRP, v)) for v in range(128)], 8))
out.append(arr("T_SRRHZ", "uint16_t", [round(SR / interp(SRRP, v)) for v in range(128)]))
# the delay's loop filter: a one-pole HP at DBAS, a one-pole LP at DBAS + DWID, 11.5 steps an octave (HP 500 Hz and
# LP 900 Hz at 64); coefficients for the line's half rate, Q15
def dhp(v):
    return 500 * 2 ** ((v - 64) / 11.5)
def dlp(v):
    return 900 * 2 ** ((v - 64) / 11.5)
out.append(arr("T_DLY_HP", "uint16_t", [round(32767 * (1 - math.exp(-2 * math.pi * min(dhp(v), 10000) / (SR / 2)))) for v in range(128)]))
out.append(arr("T_DLY_LP", "uint16_t", [32767 if dlp(v) > 10000 else round(32767 * (1 - math.exp(-2 * math.pi * dlp(v) / (SR / 2)))) for v in range(128)]))
out.append(arr("T_DBHZ", "uint16_t", [round(min(dhp(v), 65535)) for v in range(128)]))
# the filter envelope: both stages straight lines (measured: a C4 sine crossed by the swept cutoff, tools/ref/chain.py
