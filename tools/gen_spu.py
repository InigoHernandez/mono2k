def arr(name, ctype, vals, per=12):
    s = "static const %s %s[%d] = {\n" % (ctype, name, len(vals))
    for i in range(0, len(vals), per):
        s += "    " + ", ".join(str(int(v)) for v in vals[i:i + per]) + ",\n"
    return s + "};\n"


def arr2(name, ctype, rows, per=16):
    s = "static const %s %s[%d][%d] = {\n" % (ctype, name, len(rows), len(rows[0]))
    for r in rows:
        s += "    {\n"
        for i in range(0, len(r), per):
            s += "        " + ", ".join(str(int(v)) for v in r[i:i + per]) + ",\n"
        s += "    },\n"
    return s + "};\n"


def hexes(text):
    """psx-spx's notation: 'BA80h', '-001h'"""
    out = []
    for t in text.replace("\n", ",").split(","):
        t = t.strip()
        if not t:
            continue
        neg = t.startswith("-")
        v = int(t.lstrip("-").rstrip("h"), 16)
        out.append(-v if neg else v)
    return out


def s16(v):
    return v - 65536 if v >= 32768 else v


