# ----------------------------------------------------------------------------------------- the reverb's laws ---
# The nine as the console has them at each one's home (its registers exactly); MONO2K's DCAY and DAMP keep their meaning
# on every type, so a pattern moved from the FDN to a type keeps its time and colour (a proposal: docs/spu-move-plan.md):
#   DCAY: the RT60 of the FDN's law, 0.3 s x 80^((v - 1) / 126). With r = RT0 / RT (RT0 the type's own, measured:
#     host/m2k_spu_test.c --rt), the wall's gain (vWALL, the reflections' feedback) g0^r, its sign kept, at most ECHO's
#     0.992 (7F00h); and shorter than its own (r > 1) the two all-passes' gains v^r too: they ring on their own (HALL's
#     0.75 over 1684 ticks holds 1.8 s, SPACE ECHO's 3.6 s), so a short DCAY makes them less diffuse as well; longer,
#     they stay the type's. Home: the DCAY nearest RT0, its registers there exactly. DELAY has no wall (g0 0): its echoes
#     repeat for DCAY's time over its 0.742 s loop (home 1: the one echo). ECHO's 0.992 (650 s) is past DCAY's 24 s, so
#     its law runs from 0.3 s to its own at 127. 0 is off, as on the FDN
#   DAMP: the reflections' one-pole (vIIR) by its pole's log, from open (7FFFh) at 0 to 700 Hz at 127; home the DAMP
#     nearest the type's own, there its vIIR exactly
#   the level out: each type at home as loud as the FDN at the same DCAY and DAMP on the same sends (--level, bank A's
#     A02 A03 A04), and off home as the FDN's law has it, the time's fourth root over the tail's build-up (1 / (1 - g^2));
#     the echoes' (DELAY, ECHO) the same at every DCAY: their first repeat stays where it is
def rv_t60(v):                          # the FDN's (tools/gen_tables.py)
    return 0.3 * 80 ** ((v - 1) / 126.0)
def echo_t60(v, rt0):                   # ECHO's: 0.3 s .. its own
    return 0.3 * (rt0 / 0.3) ** ((v - 1) / 126.0)
