SV_IN = 2                               # the sends into the 16-bit cells: x2 (bank A's loudest, A03's, peaks -19 dBFS)
WALL_MAX = 0x7F00
L_OPEN, L_DARK = math.log(32768), 2 * math.pi * 700 / VFS   # the pole's -ln at DAMP 0 and 127
WALL, AP1, AP2, IIR, GOUT, HOME_D, HOME_P = [], [], [], [], [], [], []
for t, r in enumerate(REG):
    g0 = s16(r[R_VWALL]) / 32768.0
    a10, a20 = s16(r[R_VAPF1]), s16(r[R_VAPF2])
    loop = (r[R_MLSAME] - r[R_DLSAME]) * 4 / VFS
    if t == 8:
        home = 1
    elif t == 7:
        home = 127
    else:
        home = min(range(1, 128), key=lambda v: abs(math.log(rv_t60(v) / RT0[t])))
    w, p1, p2, go = [0], [a10], [a20], [0]
    for v in range(1, 128):
        if t == 8:                      # DELAY: its echoes for DCAY's time
            g, rr, lv = -10 ** (-3 * loop / rv_t60(v)), 1.0, 1.0
        elif t == 7:                    # ECHO: 0.3 s .. its own at 127
            rr = RT0[t] / echo_t60(v, RT0[t])
            g, lv = math.copysign(abs(g0) ** rr, g0), 1.0
        else:
            rr = RT0[t] / rv_t60(v)
            g = math.copysign(abs(g0) ** rr, g0)
            lv = (1 / rr) ** 0.25 * math.sqrt((1 - g * g) / (1 - g0 * g0))
        q = max(-WALL_MAX, min(WALL_MAX, round(g * 32768)))
        k = max(rr, 1.0)
        if v == home:
            w.append(s16(r[R_VWALL])); p1.append(a10); p2.append(a20); go.append(GO[t])
        else:
            w.append(q)
            p1.append(round(math.copysign(abs(a10 / 32768.0) ** k, a10) * 32768) if a10 else 0)
            p2.append(round(math.copysign(abs(a20 / 32768.0) ** k, a20) * 32768) if a20 else 0)
            go.append(min(32767, round(GO[t] * lv)))
    WALL.append(w); AP1.append(p1); AP2.append(p2); GOUT.append(go)
    HOME_D.append(home)
    # DAMP
    k0 = s16(r[R_VIIR]) / 32768.0
    l0 = -math.log(max(1 - k0, 1 / 32768.0))
    hp = max(0, min(127, round(127 * math.log(L_OPEN / l0) / math.log(L_OPEN / L_DARK))))
    i = []
    for d in range(128):
        l = L_OPEN * (L_DARK / L_OPEN) ** (d / 127.0)
        i.append(s16(r[R_VIIR]) if d == hp else min(32767, round(32768 * (1 - math.exp(-l)))))
    IIR.append(i)
    HOME_P.append(hp)
out.append("#define SRV_N %d\n#define SRV_IN %d\n" % (len(SV), SV_IN))
out.append(arr2("T_SRV_WALL", "int16_t", WALL, 16))
out.append(arr2("T_SRV_APF1", "int16_t", AP1, 16))
out.append(arr2("T_SRV_APF2", "int16_t", AP2, 16))
out.append(arr2("T_SRV_IIR", "int16_t", IIR, 16))
out.append(arr2("T_SRV_GOUT", "uint16_t", GOUT, 16))
out.append(arr("T_SRV_HOME_DCAY", "uint8_t", HOME_D, 9))
out.append(arr("T_SRV_HOME_DAMP", "uint8_t", HOME_P, 9))

os.makedirs(os.path.dirname(OUT), exist_ok=True)
with open(OUT, "w") as f:
    f.write("".join(out))
print("wrote", os.path.normpath(OUT))
for t, (n, _, _) in enumerate(SV):
    print("  %-10s home DCAY %3d (%.2f s) DAMP %3d, span %5d cells" % (n, HOME_D[t], RT0[t], HOME_P[t], SPAN[t]))
